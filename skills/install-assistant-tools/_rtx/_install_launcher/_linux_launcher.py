# Fixed, immutable location of the stable launch resolver beneath a given
# runtime_root. The file deployed there is officina.install.resolvers.launch's
# source (a dependency-free, stdlib-only script -- deployment is the
# managed-runtime install flow's job, not this generator's). Generated shims
# invoke this path instead of embedding a release-specific repo checkout or
# interpreter: this path does not change when the repo moves or a new release
# is activated.
_RESOLVER_RELATIVE_PATH = ("bootstrap", "resolvers", "v1", "launch.py")


def _resolver_path(*, home: Path | None = None) -> Path:
    """Return the fixed resolver path beneath this host's runtime_root."""
    home = home or Path.home()
    runtime_root = resolve_famulus_paths(platform=sys.platform, home=home).runtime_root
    return runtime_root.joinpath(*_RESOLVER_RELATIVE_PATH)


def _unix_module_content(
    module: str,
    description: str,
    *,
    home: Path | None = None,
) -> str:
    """Render one POSIX shim that delegates a module to the active release.

    The generated program intentionally knows only the stable resolver path and
    the target module. The resolver owns release selection and interpreter
    handoff, so reinstalling a release never makes this user-bin shim stale.
    """
    resolver = repr(str(_resolver_path(home=home)))
    return (
        "#!/usr/bin/env python3\n"
        "# Generated by install-assistant-tools - do not edit manually.\n"
        f'"""{description}"""\n'
        "import os\n"
        "import sys\n"
        "\n"
        f"RESOLVER = {resolver}\n"
        f"os.execv(RESOLVER, [RESOLVER, '-m', {module!r}, *sys.argv[1:]])\n"
    )


def _unix_dispatcher_content(repo_root: Path, *, home: Path | None = None) -> str:
    """Preserve the established dispatcher renderer API for external tests."""
    return _unix_module_content(
        "officina.dispatcher.cli",
        "Run officina.dispatcher.cli via the stable managed-runtime resolver.",
        home=home,
    )


def _unix_invoke_skill_content() -> str:
    return (
        "#!/usr/bin/env python3\n"
        "# Generated by install-assistant-tools - do not edit manually.\n"
        "\"\"\"Invoke a skill through the selected assistant backend.\"\"\"\n"
        "import os\n"
        "import shutil\n"
        "import sys\n"
        "from pathlib import Path\n"
        "\n"
        "if len(sys.argv) != 2:\n"
        "    print('Usage: invoke-skill <skill-name>', file=sys.stderr)\n"
        "    raise SystemExit(2)\n"
        "\n"
        "skill = sys.argv[1]\n"
        "backend = os.environ.get('ASSISTANT_DEFAULT', 'claude')\n"
        "\n"
        "\n"
        "def _repo_root():\n"
        "    \"\"\"Locate the repo holding references/. $AI when the caller set it\n"
        "    (the job executor does), else follow the assistant launcher, which\n"
        "    is a symlink back into the repo in a dev install.\"\"\"\n"
        "    ai_root = os.environ.get('AI')\n"
        "    if ai_root:\n"
        "        return Path(ai_root)\n"
        "    launcher = shutil.which('assistant')\n"
        "    if launcher:\n"
        "        resolved = Path(launcher).resolve()\n"
        "        for parent in resolved.parents:\n"
        "            # Match the file itself, not its directory: several trees\n"
        "            # under the repo carry a references/ of their own.\n"
        "            if (parent / 'references' / 'background_run.md').is_file():\n"
        "                return parent\n"
        "    return None\n"
        "\n"
        "\n"
        "def _unattended_contract():\n"
        "    \"\"\"Rules that apply only when nobody can answer a question.\n"
        "\n"
        "    invoke-skill exists for the scheduler, so every run through it is\n"
        "    unattended. The text lives in references/background_run.md -- not\n"
        "    agents/, which is a registry whose entries ship as real, dispatchable\n"
        "    agents -- and is read at launch, so editing that file changes the\n"
        "    next run with no reinstall. A missing file warns rather than failing\n"
        "    the run: losing the contract degrades a run's judgement, but\n"
        "    refusing to start guarantees the job does nothing at all.\n"
        "    \"\"\"\n"
        "    root = _repo_root()\n"
        "    path = root / 'references' / 'background_run.md' if root else None\n"
        "    try:\n"
        "        text = path.read_text(encoding='utf-8')\n"
        "        # Drop the `---` frontmatter: it names the file for humans and\n"
        "        # would otherwise reach the model as instructions.\n"
        "        parts = text.split('---', 2)\n"
        "        return (parts[2] if len(parts) >= 3 else text).strip()\n"
        "    except (AttributeError, OSError):\n"
        "        print(\n"
        "            f'invoke-skill: warning: no unattended contract at {path!s}; '\n"
        "            'this run may stop to ask a question nobody can answer',\n"
        "            file=sys.stderr,\n"
        "        )\n"
        "        return ''\n"
        "\n"
        "\n"
        "contract = _unattended_contract()\n"
        "\n"
        "if backend == 'claude':\n"
        "    command = [\n"
        "        'assistant', '--local', '--claude', '--permission-mode',\n"
        "        'bypassPermissions',\n"
        "    ]\n"
        "    if contract:\n"
        "        command += ['--append-system-prompt', contract]\n"
        "    command += ['-p', f'/{skill}']\n"
        "elif backend == 'codex':\n"
        "    # Codex has no append-system-prompt equivalent, so the contract\n"
        "    # rides in the prompt. It goes AFTER the $skill token: codex\n"
        "    # resolves that token as a skill invocation and it has to lead.\n"
        "    prompt = f'${skill}\\n\\n{contract}' if contract else f'${skill}'\n"
        "    command = [\n"
        "        'assistant', '--local', '--codex', 'exec', '--skip-git-repo-check',\n"
        "        '--dangerously-bypass-approvals-and-sandbox', prompt,\n"
        "    ]\n"
        "else:\n"
        "    print(f'Unknown ASSISTANT_DEFAULT backend: {backend}', file=sys.stderr)\n"
        "    raise SystemExit(2)\n"
        "\n"
        "try:\n"
        "    os.execvp(command[0], command)\n"
        "except FileNotFoundError:\n"
        "    print(f'Command not found: {command[0]}', file=sys.stderr)\n"
        "    raise SystemExit(127)\n"
    )


class LinuxLauncherInstaller(LauncherInstallerBase):
    """Install launcher bundles on Linux-like hosts."""

    static_launcher_mode = "link"

    def install_dispatcher_launcher(
        self,
        repo_root: Path,
        bin_dir: Path,
        dry_run: bool,
        manifest: Manifest | None = None,
        *,
        home: Path | None = None,
    ) -> LauncherInstallResult:
        bundle = LauncherBundleSpec(
            name="dispatcher",
            workflows=DISPATCHER_WORKFLOWS,
            files=[
                LauncherFileSpec(
                    destination=bin_dir / "dispatcher",
                    mode="generate",
                    content=_unix_dispatcher_content(repo_root, home=home),
                    executable=True,
                )
            ],
        )
        return self.install_bundle(bundle, dry_run=dry_run, manifest=manifest)

    def install_invoke_skill_launcher(
        self,
        bin_dir: Path,
        dry_run: bool,
        manifest: Manifest | None = None,
    ) -> LauncherInstallResult:
        bundle = LauncherBundleSpec(
            name="invoke-skill",
            workflows=INVOKE_SKILL_WORKFLOWS,
            files=[
                LauncherFileSpec(
                    destination=bin_dir / "invoke-skill",
                    mode="generate",
                    content=_unix_invoke_skill_content(),
                    executable=True,
                )
            ],
        )
        return self.install_bundle(bundle, dry_run=dry_run, manifest=manifest)

    def install_wakeup_launcher(
        self,
        bin_dir: Path,
        dry_run: bool,
        manifest: Manifest | None = None,
        *,
        home: Path | None = None,
    ) -> LauncherInstallResult:
        """Install both public wakeup names as resolver-backed POSIX shims."""
        content = _unix_module_content(
            "officina.wakeup.cli",
            "Run officina.wakeup.cli via the stable managed-runtime resolver.",
            home=home,
        )
        bundle = LauncherBundleSpec(
            name="llm-wakeup",
            workflows=WAKEUP_WORKFLOWS,
            files=[
                LauncherFileSpec(
                    destination=bin_dir / command,
                    mode="generate",
                    content=content,
                    executable=True,
                )
                for command in WAKEUP_COMMANDS
            ],
        )
        return self.install_bundle(bundle, dry_run=dry_run, manifest=manifest)

    def install_agent_launcher_files(
        self,
        *,
        source_bin_dir: Path,
        bin_dir: Path,
        agent: str,
        dry_run: bool,
        manifest: Manifest | None,
    ) -> None:
        if agent == "tw":
            bundle = LauncherBundleSpec(
                name="tw",
                required=False,
                workflows=("tmux workspace launcher",),
                files=[
                    LauncherFileSpec(
                        source=source_bin_dir / "tmux-workspace",
                        destination=bin_dir / "tmux-workspace",
                        mode=self.static_launcher_mode,
                    ),
                    LauncherFileSpec(
                        source=source_bin_dir / "tmux-workspace",
                        destination=bin_dir / "tw",
                        mode=self.static_launcher_mode,
                    ),
                ],
            )
        else:
            bundle = LauncherBundleSpec(
                name=agent,
                required=False,
                workflows=("agent launcher",),
                files=self._agent_launcher_files(source_bin_dir, bin_dir, agent),
            )
        self.install_bundle(bundle, dry_run=dry_run, manifest=manifest)
