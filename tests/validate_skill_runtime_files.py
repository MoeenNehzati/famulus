def test_gateway_ownership_requires_exact_non_python_behavioral_source(
    tmp_path: Path,
    monkeypatch,
) -> None:
    child_root = tmp_path / "skills/demo-skill/_rtx"
    jobs = child_root / "jobs.yaml"
    python_gateway = child_root / "python.yaml"
    python_payload = child_root / "bin/_owned_payload.py"
    orphan_payload = child_root / "bin/assistant"
    module_gateway = child_root / "module.yaml"
    wrong_gateway = child_root / "wrong.yaml"
    relative_paths = tuple(str(path.relative_to(tmp_path)) for path in (
        jobs,
        python_gateway,
        python_payload,
        orphan_payload,
        module_gateway,
        wrong_gateway,
    ))
    _ordered_files(monkeypatch, tmp_path, *relative_paths)
    yaml_source = "demo-skill-rtx.source.jobs"
    python_source = "demo-skill-rtx.source.python"
    mismatched_source = "demo-skill-rtx.source.wrong"
    graph = SimpleNamespace(
        module_parents={"demo-skill-rtx": "demo-skill"},
        nodes={
            "demo-skill-rtx": SimpleNamespace(module_root=child_root),
            yaml_source: SimpleNamespace(
                node_type="behavioral_source", gateway_path=jobs,
                declaration={"gateway": {"language": "YAML"}},
            ),
            python_source: SimpleNamespace(
                node_type="behavioral_source", gateway_path=python_gateway,
                declaration={"gateway": {"language": "Python"}},
            ),
            "owned-module": SimpleNamespace(
                node_type="module", gateway_path=module_gateway,
                declaration={"gateway": {"language": "YAML"}},
            ),
            mismatched_source: SimpleNamespace(
                node_type="behavioral_source", gateway_path=child_root / "other.yaml",
                declaration={"gateway": {"language": "YAML"}},
            ),
        },
        direct_file_owners={
            jobs: yaml_source,
            python_gateway: python_source,
            python_payload: python_source,
            module_gateway: "owned-module",
            wrong_gateway: mismatched_source,
        },
    )

    assert _mod.validate_with_graph(tmp_path, graph) == [
        _suffix_error(relative_paths[1], ".yaml"),
        _name_error(relative_paths[1], "filename stem", "python"),
        _name_error(relative_paths[2], "directory name", "bin"),
        _name_error(relative_paths[3], "directory name", "bin"),
        _suffix_error(relative_paths[3], ""),
        _name_error(relative_paths[3], "filename stem", "assistant"),
        _suffix_error(relative_paths[4], ".yaml"),
        _name_error(relative_paths[4], "filename stem", "module"),
        _suffix_error(relative_paths[5], ".yaml"),
        _name_error(relative_paths[5], "filename stem", "wrong"),
    ]


def test_deepest_child_and_root_module_behavior_preserves_compatibility_wrapper(
    tmp_path: Path,
) -> None:
    root = tmp_path / "modules/root"
    parent = root / "parent"
    nested = parent / "assets/nested"
    nested_fixed = nested / "assets/data.json"
    nested_payload = nested / "bin/_owned_payload.py"
    root_artifact = root / "assets/data.json"
    graph = SimpleNamespace(
        module_parents={"root": None, "parent": "root", "nested": "parent"},
        nodes={
            "root": SimpleNamespace(module_root=root),
            "parent": SimpleNamespace(module_root=parent),
            "nested": SimpleNamespace(module_root=nested),
        },
        direct_file_owners={},
    )
    index = _mod._build_child_artifact_index(graph)

    assert index == (frozenset({parent, nested}), frozenset())
    assert [_mod._is_registered_child_artifact(path, *index) for path in (
        nested_fixed, nested_payload, root_artifact,
    )] == [True, False, False]
    assert [_mod._registered_child_artifact(path, graph) for path in (
        nested_fixed, nested_payload, root_artifact,
    )] == [True, False, False]
    assert _mod._registered_child_artifact(nested_fixed, None) is False
    assert _mod._build_child_artifact_index(None) == (frozenset(), frozenset())


