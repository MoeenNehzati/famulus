def test_git_ignored_security_boundary_and_fail_closed_paths(
    tmp_path: Path,
    monkeypatch,
) -> None:
    ignored_rel = Path("skills/demo-skill/_rtx/_bad_file.sh")
    sibling_rel = Path("skills/demo-skill/_rtx/_bad_sibling.sh")
    ignored = tmp_path / ignored_rel
    sibling = tmp_path / sibling_rel
    _write(ignored)
    _write(sibling)
    monkeypatch.setattr(Path, "rglob", lambda _root, _pattern: iter((ignored, sibling)))
    outcomes = [
        SimpleNamespace(returncode=0, stdout=f"{ignored_rel.as_posix()}\0"),
        OSError("git unavailable"),
        SimpleNamespace(returncode=128, stdout=""),
    ]
    calls = []

    def fake_run(command, **kwargs):
        calls.append((command, kwargs))
        outcome = outcomes.pop(0)
        if isinstance(outcome, BaseException):
            raise outcome
        return outcome

    monkeypatch.setattr(_mod.subprocess, "run", fake_run)

    sibling_error = _suffix_error(sibling_rel.as_posix(), ".sh")
    both_errors = [
        _suffix_error(ignored_rel.as_posix(), ".sh"),
        sibling_error,
    ]
    assert _mod.validate(tmp_path) == [sibling_error]
    assert _mod.validate(tmp_path) == both_errors
    assert _mod.validate(tmp_path) == both_errors
    assert len(calls) == 3
    assert calls[0][0] == [
        "git", "-C", str(tmp_path), "ls-files", "--others", "--ignored",
        "--exclude-standard", "-z",
    ]
    assert calls[0][1] == {
        "capture_output": True, "text": True, "encoding": "utf-8",
        "errors": "replace", "check": False, "timeout": 30,
    }


def test_validation_builds_one_index_without_pairwise_root_comparisons(
    tmp_path: Path,
    monkeypatch,
) -> None:
    class CountingMapping(dict):
        items_calls = 0

        def items(self):
            self.items_calls += 1
            return super().items()

    module_parents = CountingMapping()
    direct_file_owners = CountingMapping()
    nodes = {}
    for index in range(4):
        module_id = f"child-{index}"
        child_root = tmp_path / f"skills/demo-skill/_rtx/_child_{index}"
        artifact = child_root / "assets/data.json"
        gateway = child_root / "jobs.yaml"
        _write(artifact)
        _write(gateway)
        source_id = f"{module_id}.source.jobs"
        module_parents[module_id] = "demo-skill"
        nodes[module_id] = SimpleNamespace(module_root=child_root)
        nodes[source_id] = SimpleNamespace(
            node_type="behavioral_source", gateway_path=gateway,
            declaration={"gateway": {"language": "YAML"}},
        )
        direct_file_owners[gateway] = source_id
    graph = SimpleNamespace(
        module_parents=module_parents,
        nodes=nodes,
        direct_file_owners=direct_file_owners,
    )
    original_is_relative_to = Path.is_relative_to
    pairwise_calls = []

    def counting_is_relative_to(path: Path, other: Path) -> bool:
        pairwise_calls.append((path, other))
        return original_is_relative_to(path, other)

    monkeypatch.setattr(Path, "is_relative_to", counting_is_relative_to)

    assert _mod.validate_with_graph(tmp_path, graph) == []
    assert module_parents.items_calls == 1
    assert direct_file_owners.items_calls == 1
    assert pairwise_calls == []
