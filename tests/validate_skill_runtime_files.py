"""Tests for validators/skill_runtime_files.py."""
from __future__ import annotations

import importlib.util
from pathlib import Path
from types import SimpleNamespace


_VALIDATOR = Path(__file__).resolve().parents[1] / "validators" / "skill_runtime_files.py"
_spec = importlib.util.spec_from_file_location("skill_runtime_files", _VALIDATOR)
_mod = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
_spec.loader.exec_module(_mod)


def _write(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# runtime\n", encoding="utf-8")


def _ordered_files(monkeypatch, tmp_path: Path, *relative_paths: str) -> None:
    paths = []
    for relative_path in relative_paths:
        rel_path = Path(relative_path)
        path = tmp_path / rel_path
        _write(path)
        paths.append((path, rel_path))
    monkeypatch.setattr(_mod, "_iter_skill_files", lambda _repo_root: paths)


def _name_error(relative_path: str, kind: str, component: str) -> str:
    return (
        f"{relative_path}: runtime {kind} must match "
        "`^_[A-Za-z0-9]+(?:_[A-Za-z0-9]+)+$`; "
        f"got `{component}`"
    )


def _suffix_error(relative_path: str, suffix: str) -> str:
    return (
        f"{relative_path}: unsupported runtime suffix `{suffix}`; "
        "allowed suffixes: .py"
    )


